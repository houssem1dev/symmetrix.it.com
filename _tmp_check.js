    function getSeverityTag(title, description) {
      const text = (title + " " + description).toLowerCase();
      if (text.includes("critical") || text.includes("zero-day") || text.includes("ransomware")) {
        return `<span class="tag tag-critical">Critical Risk</span>`;
      } else if (text.includes("cve") || text.includes("exploit") || text.includes("vulnerability") || text.includes("patch")) {
        return `<span class="tag tag-high">Vulnerability</span>`;
      }
      return `<span class="tag tag-info">Advisory</span>`;
    }

