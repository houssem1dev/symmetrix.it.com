    function grantCourseAccess(courseId) {
      let enrolled = JSON.parse(localStorage.getItem("symmetrix_enrolled") || "[]");
      if (!enrolled.includes(courseId)) {
        enrolled.push(courseId);
        localStorage.setItem("symmetrix_enrolled", JSON.stringify(enrolled));
      }
    }

    function openEnrolledCoursesModal() {
      if (!currentUser) {
        openAuthModal("login");
        return;
      }
      const enrolled = JSON.parse(localStorage.getItem("symmetrix_enrolled") || "[]");
      const listEl = document.getElementById("enrolled-courses-list");
      const t = translations[document.getElementById("lang-switcher").value];

      if (enrolled.length === 0) {
        listEl.innerHTML = `<p style="color:var(--text-muted); text-align:center; padding:2rem;">No courses purchased yet. Choose an academy course above to enroll.</p>`;
      } else {
        listEl.innerHTML = enrolled.map(id => {
          const c = COURSE_LOOKUP[id];
          const title = c ? t[c.titleKey] : id;
          return `
            <div style="background:var(--bg-color); border:1px solid var(--border-color); padding:1rem; border-radius:8px; display:flex; justify-content:space-between; align-items:center;">
              <div>
                <h4 style="color:#fff; font-size:1rem; margin-bottom:0.25rem;">${escapeHtml(title)}</h4>
                <span style="font-size:0.75rem; color:var(--accent-green); font-family:var(--font-mono);">Status: Active Access</span>
              </div>
              <button class="btn-primary" style="font-size:0.75rem; padding:0.4rem 0.8rem;" onclick="openCertificateModal('${escapeHtml(title)}')">View Certificate</button>
            </div>
          `;
        }).join("");
      }
      openModal("enrolled-modal");
    }

